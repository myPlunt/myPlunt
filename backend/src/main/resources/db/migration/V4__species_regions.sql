-- FMP-050: the PluntDex regions move from free text on species to their own tables, and a species can be in
-- several regions. Europe is a parent of its sub-regions: only regions without children hold countries and
-- species, and the dashboard groups the rest.
CREATE TABLE regions (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name       VARCHAR(255) NOT NULL CONSTRAINT uq_regions_name UNIQUE,
    -- Picks the region's colour in the admin dashboard.
    slug       VARCHAR(255) NOT NULL CONSTRAINT uq_regions_slug UNIQUE,
    parent_id  UUID CONSTRAINT fk_regions_parent_id REFERENCES regions(id),
    position   INT NOT NULL
);

-- Country names as the dashboard's world map spells them. The unique country keeps every country in one region.
CREATE TABLE region_countries (
    region_id  UUID NOT NULL CONSTRAINT fk_region_countries_region_id REFERENCES regions(id) ON DELETE CASCADE,
    country    VARCHAR(255) NOT NULL CONSTRAINT uq_region_countries_country UNIQUE,
    PRIMARY KEY (region_id, country)
);

CREATE TABLE species_regions (
    species_id UUID NOT NULL CONSTRAINT fk_species_regions_species_id REFERENCES species(id) ON DELETE CASCADE,
    region_id  UUID NOT NULL CONSTRAINT fk_species_regions_region_id REFERENCES regions(id),
    PRIMARY KEY (species_id, region_id)
);

CREATE INDEX idx_species_regions_region_id ON species_regions (region_id);

